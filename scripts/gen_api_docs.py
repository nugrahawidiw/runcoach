"""Generate docs/API_REFERENCE.md from the source (modules, classes, functions, docstrings).

Run from the project root:  python scripts/gen_api_docs.py
"""
from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "runcoach"
OUT = ROOT / "docs" / "API_REFERENCE.md"


def first_line(doc: str | None) -> str:
    if not doc:
        return ""
    return doc.strip().splitlines()[0].strip()


def signature(node: ast.FunctionDef) -> str:
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{node.name}({args}){returns}"


def describe_module(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    rel = path.relative_to(ROOT).as_posix()
    lines = [f"### `{rel}`", ""]
    doc = ast.get_docstring(tree)
    if doc:
        lines += [doc.strip().splitlines()[0], ""]
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            lines.append(f"- **class `{node.name}`** {first_line(ast.get_docstring(node))}".rstrip())
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                    lines.append(f"  - `{signature(item)}` {first_line(ast.get_docstring(item))}".rstrip())
        elif isinstance(node, ast.FunctionDef) and not node.name.startswith("__"):
            marker = "" if not node.name.startswith("_") else " *(private)*"
            lines.append(f"- `{signature(node)}`{marker} {first_line(ast.get_docstring(node))}".rstrip())
    lines.append("")
    return lines


def main() -> None:
    out = ["# API reference", "",
           "Generated by `scripts/gen_api_docs.py` from the source. Do not edit by hand; re-run the script.", ""]
    for path in sorted(PKG.rglob("*.py")):
        if path.name in ("__init__.py", "__main__.py") and not ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))):
            continue
        out += describe_module(path)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
